/* Pokenear static game data: rarities, series and cards.
   Shared by the browser (window.PN.data) and the Node server (require). */
(function (root) {
  'use strict';

  var TOKEN = '$POKENEAR';
  var X_HANDLE = 'pokenear';
  var SEASON_END = '2026-11-30T15:00:00Z';

  // Drop rates must sum to 1. Order is lowest -> highest tier.
  var RARITIES = [
    { id: 'C',   name: 'Common',     rate: 0.60,  burn: 5 },
    { id: 'R',   name: 'Rare',       rate: 0.25,  burn: 15 },
    { id: 'SR',  name: 'Super Rare', rate: 0.11,  burn: 50 },
    { id: 'UR',  name: 'Ultra Rare', rate: 0.035, burn: 250 },
    { id: 'SEC', name: 'Secret',     rate: 0.005, burn: 1000 }
  ];

  var ECONOMY = {
    startBonus: 1000,       // first X connect
    referredBonus: 200,     // extra for joining through an invite link
    inviteReward: 250,      // paid to the inviter per friend
    dailyReward: 200,
    dailyCooldownMs: 20 * 60 * 60 * 1000,
    singlePrice: 100,
    tenPrice: 900,
    pity: 60,               // guaranteed UR or better within this many pulls per series
    setBonus: 5000,         // complete a series binder
    historySize: 40,
    whitelistInvites: 3,
    whitelistPulls: 10
  };

  // Whitelist quests. `kind: 'x'` quests open an X intent link first.
  var TASKS = [
    { id: 'connect', title: 'Connect your X account', reward: 0, auto: true },
    { id: 'follow', title: 'Follow @' + X_HANDLE + ' on X', reward: 100, kind: 'x' },
    { id: 'post', title: 'Post your invite link on X', reward: 150, kind: 'x' },
    { id: 'invites', title: 'Invite 3 friends', reward: 0, auto: true },
    { id: 'pulls', title: 'Open 10 cards in any series', reward: 0, auto: true }
  ];

  // Real card lists come from js/cards.js (generated by scripts/build-cards.js).
  var cardsData = root.PN && root.PN.cardsData ? root.PN.cardsData : require('./cards.js');
  var SERIES = cardsData.series;

  var GAMES = {
    pokemon: { name: 'Pokémon TCG', short: 'Pokémon' },
    onepiece: { name: 'One Piece Card Game', short: 'One Piece' }
  };

  // Deterministic power from card id so it never changes between sessions.
  function hash(str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  }

  function chaseRank(c) {
    var t = rarityById[c.tier].tier * 10;
    if (c.dex || c.cat === 'CHARACTER' || c.cat === 'LEADER') t += 5;
    return t;
  }

  // Real rarity names behind each gacha tier, per game.
  var TIER_LABELS = {
    pokemon: { C: 'Common, Uncommon', R: 'Rare', SR: 'Double Rare', UR: 'Ultra Rare, Illustration Rare', SEC: 'Special Illustration, Hyper, BW and Mega Hyper Rare' },
    onepiece: { C: 'Common, Uncommon', R: 'Rare', SR: 'Super Rare, Leader', UR: 'Parallel SR and Leader, SP Card', SEC: 'Secret Rare and its parallels' }
  };

  var rarityById = {};
  RARITIES.forEach(function (r, i) { r.tier = i; rarityById[r.id] = r; });

  var cardById = {};
  var seriesById = {};
  SERIES.forEach(function (s) {
    seriesById[s.id] = s;
    s.byRarity = {};
    RARITIES.forEach(function (r) { s.byRarity[r.id] = []; });
    s.cards.forEach(function (card) {
      var r = rarityById[card.tier];
      card.series = s.id;
      // Collection score: tier weight plus a little for in-game strength.
      var strength = card.hp || (card.power ? card.power / 50 : 0) || 40;
      card.score = r.burn * 2 + Math.round(strength);
      cardById[card.id] = card;
      s.byRarity[card.tier].push(card);
    });
    // Chase cards: top tiers, one per character name, characters before trainers.
    var seen = {};
    s.chase = s.byRarity.SEC.concat(s.byRarity.UR).filter(function (c) {
      if (seen[c.name]) return false;
      seen[c.name] = true;
      return true;
    }).sort(function (a, b) { return chaseRank(b) - chaseRank(a); }).slice(0, 8);
  });

  var data = {
    TOKEN: TOKEN,
    X_HANDLE: X_HANDLE,
    SEASON_END: SEASON_END,
    RARITIES: RARITIES,
    ECONOMY: ECONOMY,
    TASKS: TASKS,
    SERIES: SERIES,
    GAMES: GAMES,
    TIER_LABELS: TIER_LABELS,
    rarityById: rarityById,
    cardById: cardById,
    seriesById: seriesById,
    hash: hash
  };

  root.PN = root.PN || {};
  root.PN.data = data;
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
