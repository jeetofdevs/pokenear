/* Near Packs static game data: card values, gacha packs and the card index.
   Shared by the browser (window.PN.data) and the Node server (require).

   Model (same as Courtyard / Collector Crypt / Phygitals):
   - Each pack has a price and a pool of cards within a value range.
   - One rip = one card. Every card in the pool has a published chance.
   - Chances are tuned so the pack's expected value is EV_RATIO x price.
   - Any pulled card can be sold back instantly for BUYBACK_RATE x its value. */
(function (root) {
  'use strict';

  var TOKEN = 'NEAR'; // payment currency shown on the site
  var VERSION = '20261022.10'; // shown in the footer and /api/config; bump with the ?v= in index.html

  // Packs are priced in US dollars and paid in NEAR through the Near Packs interaction wallet's
  // contract, which forwards every payment to the treasury. The NEAR amount of each pack is set on
  // chain (set_prices) and follows the NEAR price; the site never shows a fixed NEAR amount.
  var GAME_ACCOUNT = 'nearpacks.near'; // interaction wallet: receives payments, pays buybacks
  var TREASURY = 'nearpacks.near'; // receives every pack payment
  var CONTRACT_OWNER = 'nearpacks.near'; // owner of the Near Packs contract (prices, treasury)
  var ADMIN_ACCOUNTS = ['nearpacks.near']; // wallets that see the admin page
  var X_HANDLE = 'NearPacks'; // official X account (link only)

  // On-chain pack prices for set_prices: each pack's USD price converted to the smallest unit
  // (yoctoNEAR: 24 decimals), given the USD price of one NEAR as a decimal string. Exact BigInt math.
  function packPricesRaw(usdPerToken, decimals) {
    var m = /^(\d+)(?:\.(\d+))?$/.exec(String(usdPerToken).trim());
    if (!m || !/^\d+$/.test(String(decimals))) return null;
    var frac = m[2] || '';
    var units = BigInt(m[1] + frac);
    if (units === BigInt(0)) return null;
    var scale = BigInt(10) ** BigInt(frac.length);
    var one = BigInt(10) ** BigInt(decimals);
    return PACKS.map(function (p) { return (BigInt(Math.round(p.usd * 100)) * scale * one / (BigInt(100) * units)).toString(); });
  }

  var EV_RATIO = 0.98;      // expected card value / pack price
  var BUYBACK_RATE = 0.96;  // instant sell-back as a share of card value

  // Gacha packs, cheapest first. Every Pokémon appears in exactly one pack (see splitPacks).
  //   size: cards in the pack (legend) or cheaper "base" cards (elite, rare); chases: extra hit slots;
  //   maxHit: the most valuable card the pack may hold.
  var PACKS = [
    { id: 'starter', name: 'Starter Pack', usd: 10, chases: 6, maxHit: 75, hue: 158, tag: 'Most popular' },
    { id: 'rare', name: 'Rare Pack', usd: 25, base: 25, chases: 7, maxHit: 200, hue: 250, tag: 'Value' },
    { id: 'elite', name: 'Elite Pack', usd: 50, base: 10, chases: 6, hue: 200, tag: 'Chase' },
    { id: 'legend', name: 'Legend Pack', usd: 100, base: 0, chases: 10, hue: 158, tag: 'High roller' }
  ];
  var MULTI = [1, 5];       // rips per purchase

  // Real rarities: display code, visual tier and a base market value in USD.
  var RARITY_INFO = {
    'Common': { code: 'C', tier: 'C', usd: 0.1 },
    'Uncommon': { code: 'U', tier: 'C', usd: 0.15 },
    'Rare': { code: 'R', tier: 'R', usd: 0.4 },
    'Double rare': { code: 'RR', tier: 'SR', usd: 2.5 },
    'Illustration rare': { code: 'IR', tier: 'UR', usd: 7 },
    'Ultra Rare': { code: 'UR', tier: 'UR', usd: 9 },
    'Hyper rare': { code: 'HR', tier: 'SEC', usd: 28 },
    'Special illustration rare': { code: 'SIR', tier: 'SEC', usd: 45 },
    'Black White Rare': { code: 'BWR', tier: 'SEC', usd: 140 },
    'Mega Hyper Rare': { code: 'MUR', tier: 'SEC', usd: 220 }
  };
  // Fan favourites trade above their rarity's base value.
  var POPULAR = /^(Mega )?(Charizard|Pikachu|Mew|Mewtwo|Gengar|Eevee|Umbreon|Lugia|Rayquaza|Gardevoir|Lucario|Zekrom|Reshiram|Kyurem|Blastoise|Venusaur|Alakazam|Snorlax|Dragonite|Gyarados|Zapdos|Moltres|Articuno|Victini|Genesect|Hydreigon|Serperior)\b/;
  // Headline cards with hand-set estimates.
  var FEATURED = { 'mew-199': 320, 'meg-188': 260, 'meg-187': 210, 'blk-172': 180, 'wht-173': 170, 'mew-205': 70, 'mew-200': 90, 'mew-201': 80 };

  // Visual tiers, lowest first.
  var TIERS = [
    { id: 'C', name: 'Common' }, { id: 'R', name: 'Rare' }, { id: 'SR', name: 'Double Rare' },
    { id: 'UR', name: 'Ultra Rare' }, { id: 'SEC', name: 'Secret' }
  ];

  var HISTORY_SIZE = 60;   // recent pulls kept per player

  // Real card lists come from js/cards.js (generated by scripts/build-cards.js).
  var cardsData = root.PN && root.PN.cardsData ? root.PN.cardsData : require('./cards.js');
  var SERIES = cardsData.series;

  var GAMES = {
    pokemon: { name: 'Pokémon TCG', short: 'Pokémon' }
  };

  function hash(str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  }
  function round2(n) { return Math.round(n * 100) / 100; }

  // Estimated value: rarity base x card-specific spread (0.6-1.6) x popularity, or a hand-set figure.
  function estimateUsd(card) {
    if (FEATURED[card.id]) return FEATURED[card.id];
    var base = RARITY_INFO[card.rarity].usd;
    var spread = 0.6 + (hash(card.id) % 1000) / 1000;
    var popular = POPULAR.test(card.name) ? 1.8 : 1;
    return round2(Math.max(0.05, base * spread * popular));
  }

  var tierById = {};
  TIERS.forEach(function (t, i) { t.rank = i; tierById[t.id] = t; });

  var ALL_CARDS = [];
  var cardById = {};
  var seriesById = {};
  SERIES.forEach(function (s) {
    seriesById[s.id] = s;
    s.cards.forEach(function (card) {
      var info = RARITY_INFO[card.rarity];
      card.series = s.id;
      card.code = info.code;
      card.tier = info.tier;
      card.usd = estimateUsd(card);
      cardById[card.id] = card;
      ALL_CARDS.push(card);
    });
  });

  /* Split the cards between the packs so no Pokémon is in two packs.
     Only Pokémon cards (they all have artwork), one print per name (the most valuable), worth $5+.
     Cards under $12 are base cards: elite takes the best ones, then rare, starter gets the rest.
     Hits ($12+) go one by one, most valuable first, to the pack that still needs the most value
     per free slot to reach its expected value (+4% headroom); the top card goes to legend.
     Starter then drops its cheapest cards until its average reaches the target. Deterministic. */
  function splitPacks() {
    var best = {};
    ALL_CARDS.forEach(function (c) {
      if (c.cat !== 'Pokemon' || c.usd < 5) return;
      if (!best[c.name] || c.usd > best[c.name].usd) best[c.name] = c;
    });
    var list = Object.keys(best).map(function (k) { return best[k]; })
      .sort(function (a, b) { return b.usd - a.usd || (a.id < b.id ? -1 : 1); });
    var hits = list.filter(function (c) { return c.usd >= 12; });
    var base = list.filter(function (c) { return c.usd < 12; });
    var byId = {};
    PACKS.forEach(function (p) { byId[p.id] = p; p.cards = []; p.goal = p.usd * EV_RATIO * 1.04; });
    var at = 0;
    ['elite', 'rare'].forEach(function (id) { var p = byId[id]; p.cards = base.slice(at, at + p.base); at += p.base; });
    byId.starter.cards = base.slice(at);
    PACKS.forEach(function (p) { p.cap = p.cards.length + p.chases; });
    function sum(p) { return p.cards.reduce(function (n, c) { return n + c.usd; }, 0); }
    hits.forEach(function (c, i) {
      var pick = null, need = -Infinity;
      PACKS.forEach(function (p) {
        if (p.cards.length >= p.cap || (p.maxHit && c.usd > p.maxHit)) return;
        var n = i === 0 && p.id === 'legend' ? Infinity : (p.goal * p.cap - sum(p)) / (p.cap - p.cards.length);
        if (n > need) { need = n; pick = p; }
      });
      (pick || byId.legend).cards.push(c);
    });
    var s = byId.starter;
    s.cards.sort(function (a, b) { return b.usd - a.usd; });
    while (sum(s) / s.cards.length < s.goal) s.cards.pop();
  }

  /* Pack odds: weight each card by value^-k and pick k so the expected value hits the target.
     Cheaper cards are more likely; the chase cards are rare. Deterministic, so the browser
     and the server always publish the same odds. */
  function buildPool(pack) {
    var target = pack.usd * EV_RATIO;
    var cards = pack.cards;
    pack.min = Math.min.apply(null, cards.map(function (c) { return c.usd; }));
    function ev(k) {
      var wsum = 0, vsum = 0;
      cards.forEach(function (c) { var w = Math.pow(c.usd, -k); wsum += w; vsum += w * c.usd; });
      return vsum / wsum;
    }
    var lo = 0, hi = 8;
    for (var i = 0; i < 80; i++) {
      var mid = (lo + hi) / 2;
      if (ev(mid) > target) lo = mid; else hi = mid;
    }
    var k = (lo + hi) / 2;
    var total = 0;
    var pool = cards.map(function (c) { var w = Math.pow(c.usd, -k); total += w; return { id: c.id, w: w }; });
    var acc = 0;
    pool.forEach(function (e) { e.p = e.w / total; acc += e.p; e.cum = acc; delete e.w; });
    pool.sort(function (a, b) { return cardById[b.id].usd - cardById[a.id].usd; });
    // Re-accumulate in display order (most valuable first) for sampling.
    acc = 0;
    pool.forEach(function (e) { acc += e.p; e.cum = acc; });
    pack.pool = pool;
    pack.ev = round2(pool.reduce(function (n, e) { return n + e.p * cardById[e.id].usd; }, 0));
    // Top hits: highest values (pool already has one card per name).
    var seenName = {};
    pack.top = pool.map(function (e) { return cardById[e.id]; }).filter(function (c) {
      if (seenName[c.name]) return false;
      seenName[c.name] = 1;
      return true;
    }).slice(0, 8);
    // Chance to beat the price, and to pull 3x / 10x the price.
    function chanceAbove(x) { return pool.reduce(function (n, e) { return n + (cardById[e.id].usd >= x ? e.p : 0); }, 0); }
    pack.beat = chanceAbove(pack.usd);
    pack.x3 = chanceAbove(pack.usd * 3);
    pack.x10 = chanceAbove(pack.usd * 10);
  }
  splitPacks();
  PACKS.forEach(buildPool);
  PACKS.forEach(function (p) { delete p.cards; delete p.goal; delete p.cap; });

  var data = {
    TOKEN: TOKEN,
    GAME_ACCOUNT: GAME_ACCOUNT,
    TREASURY: TREASURY,
    CONTRACT_OWNER: CONTRACT_OWNER,
    ADMIN_ACCOUNTS: ADMIN_ACCOUNTS,
    packPricesRaw: packPricesRaw,
    VERSION: VERSION,
    EV_RATIO: EV_RATIO,
    X_HANDLE: X_HANDLE,
    BUYBACK_RATE: BUYBACK_RATE,
    PACKS: PACKS,
    MULTI: MULTI,
    RARITY_INFO: RARITY_INFO,
    TIERS: TIERS,
    HISTORY_SIZE: HISTORY_SIZE,
    SERIES: SERIES,
    ALL_CARDS: ALL_CARDS,
    GAMES: GAMES,
    tierById: tierById,
    cardById: cardById,
    seriesById: seriesById,
    packById: PACKS.reduce(function (m, p) { m[p.id] = p; return m; }, {}),
    hash: hash
  };

  root.PN = root.PN || {};
  root.PN.data = data;
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
